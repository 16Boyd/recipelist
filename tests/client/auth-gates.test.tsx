import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import AuthGate from '../../src/AuthGate'
import MfaGate from '../../src/MfaGate'

const authMocks = vi.hoisted(() => ({
  signIn: vi.fn(), signUp: vi.fn(), verifyTotp: vi.fn(), verifyBackupCode: vi.fn(), enable: vi.fn(),
}))
const apiMocks = vi.hoisted(() => ({ apiRequest: vi.fn() }))
vi.mock('../../src/authClient', () => ({ authClient: { signIn: { email: authMocks.signIn }, signUp: { email: authMocks.signUp }, twoFactor: { verifyTotp: authMocks.verifyTotp, verifyBackupCode: authMocks.verifyBackupCode, enable: authMocks.enable } } }))
vi.mock('../../src/api', () => ({ apiRequest: apiMocks.apiRequest, errorMessage: (error: unknown, fallback: string) => error instanceof Error ? error.message : fallback }))
vi.mock('qrcode', () => ({ toDataURL: vi.fn().mockResolvedValue('data:image/png;base64,qr') }))

beforeEach(() => { vi.clearAllMocks() })

describe('sign-in and account creation', () => {
  it('submits trimmed email for sign-in and shows API errors accessibly', async () => {
    const user = userEvent.setup()
    authMocks.signIn.mockResolvedValueOnce({ error: new Error('Incorrect password') })
    render(<AuthGate />)
    await user.type(screen.getByLabelText('Email'), 'person@example.com')
    await user.type(screen.getByLabelText('Password'), 'password')
    await user.click(screen.getByRole('button', { name: 'Sign in' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Incorrect password')
    expect(authMocks.signIn).toHaveBeenCalledWith({ email: 'person@example.com', password: 'password' })
  })
  it('enforces the password policy and signs up with a trimmed name and email', async () => {
    const user = userEvent.setup()
    render(<AuthGate />)
    await user.click(screen.getByRole('button', { name: /Create an account/ }))
    await user.type(screen.getByLabelText('Name'), '  Alex  ')
    await user.type(screen.getByLabelText('Email'), 'alex@example.com')
    await user.type(screen.getByLabelText('Password'), 'weakpassword')
    await user.click(screen.getByRole('button', { name: 'Create account' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Use at least 12 characters')
    expect(authMocks.signUp).not.toHaveBeenCalled()
    await user.clear(screen.getByLabelText('Password'))
    await user.type(screen.getByLabelText('Password'), 'GoodPassword12!')
    authMocks.signUp.mockResolvedValueOnce({ data: {} })
    await user.click(screen.getByRole('button', { name: 'Create account' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Your account was created')
    expect(authMocks.signUp).toHaveBeenCalledWith({ name: 'Alex', email: 'alex@example.com', password: 'GoodPassword12!' })
  })
  it('supports TOTP challenge and switching to backup-code verification', async () => {
    const user = userEvent.setup()
    authMocks.signIn.mockResolvedValueOnce({ data: { twoFactorRedirect: true } })
    authMocks.verifyBackupCode.mockResolvedValueOnce({ data: {} })
    render(<AuthGate />)
    await user.type(screen.getByLabelText('Email'), 'alex@example.com')
    await user.type(screen.getByLabelText('Password'), 'GoodPassword12!')
    await user.click(screen.getByRole('button', { name: 'Sign in' }))
    expect(await screen.findByRole('heading', { name: 'Verify your authenticator.' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Use a backup code' }))
    await user.type(screen.getByLabelText('Backup code'), 'AB123-CD456')
    await user.click(screen.getByRole('button', { name: 'Continue' }))
    await waitFor(() => expect(authMocks.verifyBackupCode).toHaveBeenCalledWith({ code: 'AB123-CD456', trustDevice: false }))
    expect(screen.getByRole('heading', { name: 'Welcome back.' })).toBeInTheDocument()
  })
  it('validates and submits a six-digit authenticator code', async () => {
    const user = userEvent.setup()
    authMocks.signIn.mockResolvedValueOnce({ data: { twoFactorRedirect: true } })
    authMocks.verifyTotp.mockResolvedValueOnce({ data: {} })
    render(<AuthGate />)
    await user.type(screen.getByLabelText('Email'), 'alex@example.com')
    await user.type(screen.getByLabelText('Password'), 'password')
    await user.click(screen.getByRole('button', { name: 'Sign in' }))
    await screen.findByRole('heading', { name: 'Verify your authenticator.' })
    const codeInput = screen.getByLabelText('6-digit code')
    await user.type(codeInput, '123')
    await user.click(screen.getByRole('button', { name: 'Continue' }))
    expect(codeInput).toHaveProperty('validity.patternMismatch', true)
    expect(authMocks.verifyTotp).not.toHaveBeenCalled()
    await user.clear(codeInput)
    await user.type(codeInput, '654321')
    await user.click(screen.getByRole('button', { name: 'Continue' }))
    await waitFor(() => expect(authMocks.verifyTotp).toHaveBeenCalledWith({ code: '654321', trustDevice: false }))
    expect(screen.getByRole('heading', { name: 'Welcome back.' })).toBeInTheDocument()
  })
})

describe('MFA enrollment gate', () => {
  it('requires saved backup codes before verifying enrollment and completes setup after TOTP', async () => {
    const user = userEvent.setup()
    authMocks.enable.mockResolvedValueOnce({ data: { method: 'totp', totpURI: 'otpauth://totp/RecipeList?secret=ABC123', backupCodes: ['AAAAA-BBBBB'] } })
    authMocks.verifyTotp.mockResolvedValueOnce({ data: {} })
    apiMocks.apiRequest.mockResolvedValueOnce(undefined)
    const complete = vi.fn()
    render(<MfaGate userId="u1" email="alex@example.com" onSetupComplete={complete} onSignOut={vi.fn()} signingOut={false} accountError="" />)
    await user.type(screen.getByLabelText('Confirm your password'), 'MyPassword')
    await user.click(screen.getByRole('button', { name: 'Set up authenticator app' }))
    expect(await screen.findByText('AAAAA-BBBBB')).toBeInTheDocument()
    const verifyButton = screen.getByRole('button', { name: 'Verify and finish setup' })
    expect(verifyButton).toBeDisabled()
    await user.click(screen.getByLabelText('I saved these codes'))
    expect(verifyButton).toBeEnabled()
    await user.type(screen.getByLabelText('6-digit code'), '123456')
    await user.click(verifyButton)
    await waitFor(() => expect(apiMocks.apiRequest).toHaveBeenCalledWith('/api/mfa/complete-setup', { method: 'POST', body: '{}' }))
    expect(complete).toHaveBeenCalledOnce()
  })
  it('renders account errors and permits sign-out', async () => {
    const signOut = vi.fn()
    render(<MfaGate userId="u2" email="" onSetupComplete={vi.fn()} onSignOut={signOut} signingOut={false} accountError="Account check failed" />)
    expect(screen.getByRole('alert')).toHaveTextContent('Account check failed')
    fireEvent.click(screen.getByRole('button', { name: 'Sign out' }))
    expect(signOut).toHaveBeenCalledOnce()
  })
})
